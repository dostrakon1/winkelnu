#!/usr/bin/env node

import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const root = process.cwd()
const imageDirectory = join(root, 'public', 'images', 'categories')
const outputPath = join(root, 'src', 'generated', 'category-image-manifest.ts')
const filePattern = /^([a-z0-9]+(?:-[a-z0-9]+)*)-hero\.webp$/

const slugs = readdirSync(imageDirectory, { withFileTypes: true })
  .filter((entry) => entry.isFile())
  .map((entry) => entry.name.match(filePattern)?.[1] ?? null)
  .filter(Boolean)
  .sort((left, right) => left.localeCompare(right, 'nl'))

if (slugs.length === 0) {
  throw new Error('Geen categorie-afbeeldingen gevonden in public/images/categories')
}

const content = [
  '// AUTO-GENERATED by scripts/generate-category-image-manifest.mjs.',
  '// Do not edit manually. Add/remove correctly named files in public/images/categories instead.',
  'export const categoryImageSlugs = [',
  ...slugs.map((slug) => `  '${slug}',`),
  '] as const',
  '',
].join('\n')

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, content, 'utf8')
console.log(`✓ Categoriebeeldmanifest bijgewerkt (${slugs.length} afbeeldingen)`)
